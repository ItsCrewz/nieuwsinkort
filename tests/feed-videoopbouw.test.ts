import assert from "node:assert/strict";
import { dumpertEmbed, parseDumpert, parseIgProfile, igVideo, igVideoUrl, kortGetal, soortVan } from "../worker/src/videos";
import { redlibPath, redlibToAtom } from "../worker/src/redlib";
import { parseRedditVideos } from "../worker/src/reddit";

const variant = (version: string, uri: string) => ({ version, uri });
assert.equal(kortGetal(null, "views"), "");
assert.equal(kortGetal(1250, "views"), "1,3k views");
assert.equal(kortGetal(2000000, "views"), "2M views");
assert.equal(dumpertEmbed({ media: [{ mediatype: "VIDEO", variants: [variant("mobile", "https://cdn.nl/m.mp4"), variant("720p", "https://cdn.nl/h.mp4")] }] }), "https://cdn.nl/h.mp4");
assert.equal(dumpertEmbed({ media: [{ mediatype: "VIDEO", variants: [variant("stream", "https://cdn.nl/v.m3u8?x=1")] }] }), "https://cdn.nl/v.m3u8?x=1");
assert.equal(dumpertEmbed({ media: [{ mediatype: "YOUTUBE", variants: [variant("", "abcdefghijk")] }] }), "https://www.youtube-nocookie.com/embed/abcdefghijk?autoplay=1&rel=0");
assert.equal(dumpertEmbed({ media: [{ mediatype: "IMAGE", variants: [variant("", "https://cdn.nl/a.mp4")] }] }), "");
const clip = (id: string, kudos: number, extra = {}) => ({ id, title: ` Video ${id} `, published_at: "2026-10-29T10:00:00Z", stats: { views_today: 1200, kudos_today: kudos }, media: [{ mediatype: "VIDEO", variants: [variant("mobile", "https://cdn.nl/v.mp4")] }], ...extra });
const data = { state: { "list=toppers": { data: { result: { data: { items: [clip("a", 2), clip("b", 9), clip("c", 99, { nsfw: true }), clip("d", 0, { stats: {} })] } } } } } };
const html = `window.__DUMPERT_CONTEXT__ = JSON.parse(${JSON.stringify(JSON.stringify(data))})`;
const toppers = parseDumpert(html, () => "11:00");
assert.deepEqual(toppers.map((v) => v.titel), ["Video b", "Video a"]);
assert.equal(toppers[0].populariteit, "1,2k views · 9 kudos");
assert.throws(() => parseDumpert("", () => ""), /geen __DUMPERT_CONTEXT__/);
assert.throws(() => parseDumpert(`window.__DUMPERT_CONTEXT__ = JSON.parse(${JSON.stringify(JSON.stringify({ state: {} }))})`, () => ""), /geen toppers-lijst/);
const context = { context: { username: "nieuws", graphql_media: [{ shortcode_media: { shortcode: "abc", is_video: true, taken_at_timestamp: 100, edge_media_to_caption: { edges: [{ node: { text: "Een bericht over het nieuws. Meer informatie. #nieuws" } }] }, display_url: "https://cdn.nl/foto.jpg", edge_liked_by: { count: 12 } } }] } };
const posts = parseIgProfile(`"contextJSON":${JSON.stringify(JSON.stringify(context))}`);
assert.equal(posts[0].user, "nieuws");
assert.equal(posts[0].t, 100000);
const video = igVideo(posts[0], "https://cdn.nl/v.mp4", "Nieuws", () => "11:00");
assert.equal(video.titel, "Een bericht over het nieuws.");
assert.equal(video.ai, "Meer informatie.");
assert.equal(video._score, 240);
assert.equal(igVideoUrl('"video_url":"https:\\/\\/cdn.nl\\/v.mp4?x=1\\u0026y=2"'), "https://cdn.nl/v.mp4?x=1&y=2");
assert.equal(igVideoUrl("geen video"), "");
assert.throws(() => parseIgProfile(""), /geen Instagram-embeddata/);
assert.equal(soortVan({ titel: "NOS Journaal" }), "journaal");
assert.equal(soortVan({ href: "https://youtube.com/shorts/abcdefghijk" }), "short");
assert.equal(redlibPath("https://www.reddit.com/r/europe/top/.rss?t=day"), "/r/europe/top?t=day");
assert.equal(redlibPath("https://voorbeeld.nl/"), null);
assert.equal(redlibToAtom("botcheck", "lokaal"), null);
const redlib = '<div class="post" id="abc123"><h2 class="post_title"><a href="/r/europe/comments/abc123/titel">Nieuws &amp; video</a></h2><span class="created" title="2026-10-29T10:00:00Z"><video src="/vid/vid123/a"><img poster="/preview/pre/foto.jpg">';
const atom = redlibToAtom(redlib, "lokaal");
assert.ok(atom);
const reddit = parseRedditVideos(atom, "europe", Date.parse("2026-10-28T00:00:00Z"), () => "11:00");
assert.equal(reddit.length, 1);
assert.equal(reddit[0].embed, "https://v.redd.it/vid123/HLSPlaylist.m3u8");
assert.equal(reddit[0].thumb, "https://preview.redd.it/foto.jpg");
