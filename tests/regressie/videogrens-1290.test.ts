import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { act, createElement } from "react";
import { zetNepDom } from "../hulp/nepdom";

const fixture = JSON.parse(readFileSync("public/data.json", "utf8"));
const dom = zetNepDom({});
const gebeurtenissen = new EventTarget();
dom.doc.addEventListener = gebeurtenissen.addEventListener.bind(gebeurtenissen);
dom.doc.removeEventListener = gebeurtenissen.removeEventListener.bind(gebeurtenissen);
const echtNu = Date.now, echteSet = globalThis.setTimeout, echteClear = globalThis.clearTimeout;
let nu = Date.parse("2026-03-29T09:00:00+02:00"), teller = 0;
const timers = new Map<number, { fn: () => void; ms: number }>();
Date.now = () => nu;
globalThis.setTimeout = ((fn: () => void, ms: number) => { const id = ++teller; timers.set(id, { fn, ms }); return id; }) as typeof setTimeout;
globalThis.clearTimeout = ((id: number) => { timers.delete(id); }) as typeof clearTimeout;
window.setInterval = (() => 42) as typeof window.setInterval;
window.clearInterval = (() => {}) as typeof window.clearInterval;
let inhoud = { ...fixture, filmpjes: [], dumpert: [] };
globalThis.fetch = (async () => Response.json(inhoud)) as typeof fetch;
const { createRoot } = await import("react-dom/client");
const { useData } = await import("../../src/App");
let toestand!: ReturnType<typeof useData>;
function Proef() { toestand = useData(); return null; }
const root = createRoot(dom.container as unknown as Element);
await act(async () => root.render(createElement(Proef)));
assert.equal(timers.size, 0, "zonder gisteren-video's geen grenstimer");
const video = fixture.filmpjes[0];
assert.ok(video, "fixture bevat een filmpje");
inhoud = { ...inhoud, filmpjes: [{ ...video, gisteren: true }, { ...video, gisteren: false, titel: "Heel ander onderwerp over haven en wind", ai: "Een compleet ander bericht.", href: "https://www.youtube.com/watch?v=abcdefghijk", embed: "https://www.youtube-nocookie.com/embed/abcdefghijk?autoplay=1&rel=0", thumb: "https://i.ytimg.com/vi/abcdefghijk/hqdefault.jpg" }] };
await act(async () => { await toestand.reload(); });
assert.equal(timers.size, 1);
assert.equal([...timers.values()][0].ms, 3600e3, "timer op 10:00 na de zomertijdwisseling");
const oudeTimer = [...timers.keys()][0];
inhoud = { ...inhoud, dag_samenvatting: "Nieuwe data" };
await act(async () => { await toestand.reload(); });
assert.equal(timers.size, 1);
assert.ok(!timers.has(oudeTimer), "nieuwe data ruimt de oude timer op");
dom.doc.visibilityState = "hidden";
nu = Date.parse("2026-03-29T10:01:00+02:00");
dom.doc.visibilityState = "visible";
await act(async () => { gebeurtenissen.dispatchEvent(new Event("visibilitychange")); });
assert.equal(toestand.data?.filmpjes?.length, 1, "terugkeer verwijdert alleen de verlopen video");
assert.equal(timers.size, 0, "na verwijderen geen grenstimer meer");
await act(async () => root.unmount());
Date.now = echtNu; globalThis.setTimeout = echteSet; globalThis.clearTimeout = echteClear;
console.log("✓ grenstimer volgt data en zichtbaarheid");
