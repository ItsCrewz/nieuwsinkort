import assert from "node:assert/strict";
import { volgFeedHerstel } from "../../src/video";
import type { FeedStatus } from "../../src/feedstatus";
import type { Video } from "../../src/types";

// Bestaand filmpje uit de fixture filmpjes-live-31-10.json.
const filmpje = { titel: "Karen Damen schiet vol tijdens act Dehaze in Got Talent | RTL Boulevard", bron: "YouTube", href: "https://www.youtube.com/shorts/fDsyJufbePY", soort: "short" } as Video;
const sleutel = "yt-fDsyJufbePY";
const g = globalThis as any;
const win = new EventTarget() as any;
const doc = new EventTarget() as any;
let tik = () => {};
let opgeslagen: FeedStatus | null = null;
let gepauzeerd = false;
const speler = { readyState: 1, currentTime: 0, paused: false, pause() { gepauzeerd = true; } };
win.setInterval = (fn: () => void) => { tik = fn; return 1; };
win.clearInterval = () => {};
g.window = win; g.document = doc;
g.location = { hash: "#/filmpjes/yt%2DfDsyJufbePY" };
g.history = { state: null, replaceState() {} };
g.sessionStorage = { setItem(_key: string, waarde: string) { opgeslagen = JSON.parse(waarde); } };
doc.visibilityState = "visible";
doc.querySelector = () => ({ querySelector: (selector: string) => selector === "video" ? speler : null });
const saved: FeedStatus = { cat: "filmpjes", slug: sleutel, soort: "short", positie: 42, speelt: true, lijst: [filmpje] };
const stop = volgFeedHerstel(sleutel, "filmpjes", [filmpje], sleutel, saved);
assert.equal(speler.currentTime, 42);
assert.equal((opgeslagen as FeedStatus | null)?.slug, sleutel);
speler.currentTime = 48;
g.location.hash = "#/filmpjes/%E0%A4%A";
assert.doesNotThrow(() => tik());
assert.equal((opgeslagen as FeedStatus | null)?.slug, sleutel);
assert.equal((opgeslagen as FeedStatus | null)?.positie, 48);
speler.currentTime = 51;
assert.doesNotThrow(() => win.dispatchEvent(new Event("pagehide")));
assert.equal((opgeslagen as FeedStatus | null)?.slug, sleutel);
assert.equal((opgeslagen as FeedStatus | null)?.positie, 51);
assert.equal(gepauzeerd, true);
stop();
console.log("✓ Ongeldige videohash tijdens positiebewaring (#1256)");
