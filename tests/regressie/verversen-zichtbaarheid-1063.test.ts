import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { act, createElement } from "react";
import { zetNepDom } from "../hulp/nepdom";

const fixture = JSON.parse(readFileSync("public/data.json", "utf8"));
const dom = zetNepDom({});
const gebeurtenissen = new EventTarget();
dom.doc.addEventListener = gebeurtenissen.addEventListener.bind(gebeurtenissen);
dom.doc.removeEventListener = gebeurtenissen.removeEventListener.bind(gebeurtenissen);
let tik!: () => void;
let opgeruimd = false;
window.setInterval = ((fn: () => void, ms: number) => { assert.equal(ms, 15 * 60 * 1000); tik = fn; return 42; }) as typeof window.setInterval;
window.clearInterval = ((id: number) => { assert.equal(id, 42); opgeruimd = true; }) as typeof window.clearInterval;
const aanvragen: Array<(r: Response) => void> = [];
globalThis.fetch = (() => new Promise<Response>((resolve) => aanvragen.push(resolve))) as typeof fetch;
const { createRoot } = await import("react-dom/client");
const { useData } = await import("../../src/App");
let toestand!: ReturnType<typeof useData>;
function Proef() { toestand = useData(); return null; }
const root = createRoot(dom.container as unknown as Element);
const antwoord = (tekst: string) => Response.json({ ...fixture, dag_samenvatting: tekst });
await act(async () => root.render(createElement(Proef)));
assert.equal(aanvragen.length, 1);
await act(async () => { tik(); });
assert.equal(aanvragen.length, 2, "zichtbaar tabblad ververst periodiek");
dom.doc.visibilityState = "hidden";
await act(async () => { gebeurtenissen.dispatchEvent(new Event("visibilitychange")); tik(); tik(); });
assert.equal(aanvragen.length, 2, "verborgen tabblad slaat periodieke aanvragen over");
await act(async () => { void toestand.reload(); });
assert.equal(aanvragen.length, 3, "handmatig verversen blijft mogelijk");
dom.doc.visibilityState = "visible";
await act(async () => { gebeurtenissen.dispatchEvent(new Event("visibilitychange")); });
assert.equal(aanvragen.length, 4, "terugkeer start één aanvraag");
await act(async () => { aanvragen[3](antwoord("Actueel")); });
await act(async () => { aanvragen[0](antwoord("Verouderd")); aanvragen[1](antwoord("Verouderd")); aanvragen[2](antwoord("Verouderd")); });
assert.equal(toestand.data?.dag_samenvatting, "Actueel", "late antwoorden worden genegeerd");
await act(async () => root.unmount());
assert.equal(opgeruimd, true, "timer is opgeruimd");
gebeurtenissen.dispatchEvent(new Event("visibilitychange"));
assert.equal(aanvragen.length, 4, "luisteraar is opgeruimd");
console.log("✓ verversen bij zichtbaarheid en opruimen");
