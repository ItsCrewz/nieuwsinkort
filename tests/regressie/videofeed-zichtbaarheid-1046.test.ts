import assert from "node:assert/strict";
import { act, createElement } from "react";
import { Knoop, zetNepDom } from "../hulp/nepdom";
import fixture from "./fixtures/video-miniatuur-790.json";

const dom = zetNepDom({});
const gebeurtenissen = new EventTarget();
dom.doc.addEventListener = gebeurtenissen.addEventListener.bind(gebeurtenissen);
dom.doc.removeEventListener = gebeurtenissen.removeEventListener.bind(gebeurtenissen);
const berichten: string[] = [];
const videos: Knoop[] = [];
const pauzes = new Map<Knoop, number>();
const maakElement = dom.doc.createElement;
dom.doc.createElement = (tag: string) => {
  const element: Knoop = maakElement(tag);
  element.querySelectorAll = (selector: string) => selector === "iframe.f-yt"
    ? element.vind((n) => n.nodeName === "iframe" && (n.getAttribute("class") ?? "").split(" ").includes("f-yt")) : [];
  if (tag === "iframe") element.contentWindow = { postMessage: (bericht: string) => berichten.push(JSON.parse(bericht).func) };
  if (tag === "video") {
    videos.push(element);
    element.pause = () => { pauzes.set(element, (pauzes.get(element) ?? 0) + 1); element.paused = true; };
  }
  return element;
};
const { createRoot } = await import("react-dom/client");
const { Feed } = await import("../../src/feed");
const root = createRoot(dom.container as unknown as Element);
await act(async () => root.render(createElement(Feed, { list: [{ ...fixture, ai: "", populariteit: "", tijd: "" }], cat: "filmpjes", start: null, onClose: () => {} })));
assert.equal(dom.doc.body.vind((n: Knoop) => n.nodeName === "iframe").length, 1, "de fake hoort bij de gemounte YouTube-speler");
assert.equal(videos.length, 3);
const iframe = dom.doc.body.vind((n: Knoop) => n.nodeName === "iframe")[0];
const klaar = Object.assign(new Event("message"), { origin: "https://www.youtube-nocookie.com", source: iframe.contentWindow, data: { event: "onReady" } });
await act(async () => window.dispatchEvent(klaar));
const toets = (key: string) => window.dispatchEvent(Object.assign(new Event("keydown", { cancelable: true }), { key }));
const verberg = async () => act(async () => { dom.doc.hidden = true; gebeurtenissen.dispatchEvent(new Event("visibilitychange")); });
const toon = async () => act(async () => { dom.doc.hidden = false; gebeurtenissen.dispatchEvent(new Event("visibilitychange")); });
const voor = videos.map((v) => pauzes.get(v) ?? 0);
berichten.length = 0;
await verberg();
assert.deepEqual(videos.map((v, i) => (pauzes.get(v) ?? 0) - voor[i]), [1, 1, 1]);
assert.ok(berichten.includes("pauseVideo"));
assert.ok(!berichten.includes("seekTo"));
await toon();
await verberg();
await toon();
assert.ok(!berichten.includes("seekTo"), "snelle wisselingen veranderen de positie niet");
berichten.length = 0;
await act(async () => window.dispatchEvent(new Event("pagehide")));
assert.ok(berichten.includes("pauseVideo"));
await act(async () => window.dispatchEvent(new Event("pageshow")));
assert.ok(!berichten.includes("seekTo"));
await act(async () => toets(" "));
berichten.length = 0;
await verberg();
await toon();
assert.ok(!berichten.includes("playVideo"), "handmatig gepauzeerde YouTube blijft gepauzeerd");
await verberg();
berichten.length = 0;
await act(async () => { toets("ArrowDown"); toets("Escape"); });
assert.ok(!berichten.includes("playVideo"), "wisselen en sluiten op de achtergrond starten niet");
await act(async () => root.unmount());
console.log("✓ videofeed pauzeert bij zichtbaarheidwisselingen zonder positie-reset (#1046)");
