import assert from "node:assert/strict";
import { artikelUrl, deel } from "../src/delen";
const url = artikelUrl({ kop: "Nieuws", bronnen: [{ href: "https://bron.nl/a" }] }, "2026-11-04");
assert.ok(url.startsWith("https://nieuwsinkort.nl/bericht/"));
let gedeeld = "", gekopieerd = "";
assert.equal(await deel({ share: async (d) => { gedeeld = d.url || ""; } }, "Titel", url), "gedeeld");
assert.equal(gedeeld, url);
assert.equal(await deel({ share: async () => { throw new DOMException("", "AbortError"); }, clipboard: { writeText: async () => { throw Error(); } } }, "Titel", url), "geannuleerd");
assert.equal(await deel({ share: async () => { throw Error(); }, clipboard: { writeText: async (s) => { gekopieerd = s; } } }, "Titel", url), "gekopieerd");
assert.equal(gekopieerd, url);
assert.equal(await deel({ clipboard: { writeText: async () => { throw Error(); } } }, "Titel", url), "handmatig");
let shareAangeroepen = false;
const share = async () => { shareAangeroepen = true; };
const canShare = () => { throw new DOMException("", "AbortError"); };
gekopieerd = "";
assert.equal(await deel({ share, canShare, clipboard: { writeText: async (s) => { gekopieerd = s; } } }, "Titel", url), "gekopieerd");
assert.equal(gekopieerd, url);
assert.equal(await deel({ share, canShare, clipboard: { writeText: async () => { throw Error(); } } }, "Titel", url), "handmatig");
assert.equal(shareAangeroepen, false);
// Klembord dat nooit antwoordt (#1315): na de time-out volgt de handmatige terugval; late resultaten veranderen niets.
let laatOk: () => void = () => {}, laatFout: (e: Error) => void = () => {};
const start = Date.now();
assert.equal(await deel({ clipboard: { writeText: () => new Promise<void>(() => {}) } }, "Titel", url, 30), "handmatig");
assert.ok(Date.now() - start < 1000);
assert.equal(await deel({ clipboard: { writeText: () => new Promise<void>((ok) => { laatOk = ok; }) } }, "Titel", url, 30), "handmatig");
laatOk();
assert.equal(await deel({ clipboard: { writeText: () => new Promise<void>((_, nee) => { laatFout = nee; }) } }, "Titel", url, 30), "handmatig");
laatFout(new Error("laat"));
await new Promise((r) => setTimeout(r, 20));
assert.equal(await deel({ clipboard: { writeText: () => new Promise<void>((ok) => setTimeout(ok, 5)) } }, "Titel", url, 200), "gekopieerd");
